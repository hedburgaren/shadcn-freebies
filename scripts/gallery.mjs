// Checks catalog.yaml and writes the index section of readme.md from it.
//
// Usage, from this directory:
//   node gallery.mjs           check the catalog and rewrite the index
//   node gallery.mjs --check   check the catalog only
//
// Only the part of readme.md between the gallery markers is replaced.
// Entries with status candidate are left out of the index. The script exits
// non-zero, and writes nothing, when the catalog has errors.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const START = "<!-- gallery:start -->";
const END = "<!-- gallery:end -->";
const IMAGE_WIDTH = 400;
const COLUMNS = 2;
const FREE = { full: "Free", partial: "Free tier, paid tier alongside", unknown: "Free status unknown" };
const STATUSES = ["candidate", "verified", "screenshotted"];
const REQUIRED = ["slug", "name", "url", "category", "free", "status", "source"];
const LINKS = ["url", "repo", "demo"];

const read = (file) => readFileSync(join(ROOT, file), "utf8");
const html = (value) =>
  String(value).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

function check(entries, categories) {
  const errors = [];
  const known = new Set(categories.map((c) => c.slug));
  const seen = new Set();
  for (const e of entries) {
    const at = `entry ${e.slug ?? "(no slug)"}`;
    for (const field of REQUIRED) if (!e[field]) errors.push(`${at}: missing ${field}`);
    if (e.slug && !/^[a-z0-9]+(-[a-z0-9]+)*$/.test(e.slug)) errors.push(`${at}: slug is not kebab-case`);
    if (seen.has(e.slug)) errors.push(`${at}: duplicate slug`);
    seen.add(e.slug);
    if (e.category && !known.has(e.category)) errors.push(`${at}: unknown category ${e.category}`);
    if (e.free && !(e.free in FREE)) errors.push(`${at}: free must be one of ${Object.keys(FREE).join(", ")}`);
    if (e.status && !STATUSES.includes(e.status)) errors.push(`${at}: status must be one of ${STATUSES.join(", ")}`);
    for (const field of LINKS) if (e[field] && !e[field].startsWith("https://")) errors.push(`${at}: ${field} is not https`);
    if (e.screenshot && !existsSync(join(ROOT, e.screenshot))) errors.push(`${at}: screenshot file missing`);
    if (Boolean(e.screenshot) !== (e.status === "screenshotted")) errors.push(`${at}: screenshot and status disagree`);
  }
  return errors;
}

function card(e) {
  const lines = [];
  if (e.screenshot) {
    lines.push(`<a href="${html(e.url)}"><img src="${e.screenshot}" alt="${html(e.name)}" width="${IMAGE_WIDTH}"></a><br>`);
  }
  lines.push(`<b><a href="${html(e.url)}">${html(e.name)}</a></b><br>`);
  if (e.description) lines.push(`${html(e.description)}<br>`);
  const meta = [e.license ? html(e.license) : "No license found", FREE[e.free]];
  if (e.repo && e.repo !== e.url) meta.push(`<a href="${html(e.repo)}">Repository</a>`);
  if (e.demo) meta.push(`<a href="${html(e.demo)}">Demo</a>`);
  lines.push(`<sub>${meta.join(" · ")}</sub>`);
  if (e.notes) lines.push(`<br><sub>${html(e.notes)}</sub>`);
  return lines.join("\n");
}

function table(entries) {
  const rows = [];
  for (let i = 0; i < entries.length; i += COLUMNS) {
    const cells = entries.slice(i, i + COLUMNS).map((e) => `<td width="50%" valign="top">\n${card(e)}\n</td>`);
    while (cells.length < COLUMNS) cells.push(`<td width="50%"></td>`);
    rows.push(`<tr>\n${cells.join("\n")}\n</tr>`);
  }
  return `<table>\n${rows.join("\n")}\n</table>`;
}

function gallery(entries, categories) {
  const listed = entries.filter((e) => e.status !== "candidate");
  const groups = categories
    .map((c) => ({
      ...c,
      entries: listed
        .filter((e) => e.category === c.slug)
        .sort((a, b) => a.name.localeCompare(b.name, "en", { sensitivity: "base" })),
    }))
    .filter((c) => c.entries.length);
  const anchor = (title) => title.toLowerCase().replace(/[^a-z0-9 -]/g, "").replace(/ /g, "-");
  const contents = groups.map((c) => `[${c.title}](#${anchor(c.title)}) (${c.entries.length})`).join(" · ");
  const parts = [
    "<!-- Generated by scripts/gallery.mjs from catalog.yaml. Edit the catalog, not this section. -->",
    `${listed.length} resources in ${groups.length} categories: ${contents}`,
  ];
  for (const c of groups) parts.push(`### ${c.title}`, c.description, table(c.entries));
  return parts.join("\n\n");
}

const entries = parse(read("catalog.yaml"));
const categories = parse(read("categories.yaml"));
const errors = check(entries, categories);
if (errors.length) {
  console.error(errors.join("\n"));
  console.error(`\n${errors.length} error(s) in catalog.yaml; readme.md not changed`);
  process.exit(1);
}
console.log(`catalog.yaml: ${entries.length} entries, no errors`);
if (process.argv.includes("--check")) process.exit(0);

const readme = read("readme.md");
const start = readme.indexOf(START);
const end = readme.indexOf(END);
if (start === -1 || end === -1 || end < start) {
  console.error(`readme.md needs the markers ${START} and ${END}`);
  process.exit(1);
}
const next = `${readme.slice(0, start + START.length)}\n${gallery(entries, categories)}\n${readme.slice(end)}`;
writeFileSync(join(ROOT, "readme.md"), next);
console.log(next === readme ? "readme.md already up to date" : "readme.md index rewritten");
